classdef IntelligentJammerFactory
    methods (Static)
        %% ========== IntelligentJammer 생성 ==========
        function ijNode = createIntelligentJammer( ...
                UTs, ...
                Beams, ...
                targetUTId, ...
                targetJammerDistance)

            % Target UT
            targetUT = UTs(targetUTId);

            % Target UT 위치
            targetPosition = targetUT.getPosition();

            % Target UT가 속한 Beam
            targetBeam = Beams(targetUT.AssociatedBeamId);

            % IJ 위치 생성
            ijPosition = ...
                IntelligentJammerFactory.generateIJPosition( ...
                    targetPosition, ...
                    targetBeam, ...
                    targetJammerDistance);

            % IntelligentJammer 객체 생성
            ijNode = ...
                IntelligentJammer( ...
                    7777, ...
                    ijPosition, ...
                    targetUTId);
        end

        %% ========== IJ 위치 생성 ==========
        function position = generateIJPosition( ...
                targetPosition, ...
                targetBeam, ...
                targetJammerDistance)

            maxPlacementAttempts = 10000;
            isPlaced = false;
            attemptCount = 0;

            while ~isPlaced
                attemptCount = attemptCount + 1;

                if attemptCount > maxPlacementAttempts
                    error( ...
                        "IntelligentJammerFactory:PlacementFailed", ...
                        [ ...
                            "Target UT로부터 %.2f km 거리이면서 " ...
                            "Beam %d 내부인 IJ 위치를 찾지 못했습니다." ...
                        ], ...
                        targetJammerDistance / 1e3, ...
                        targetBeam.Id);
                end

                randomAngle = 2 * pi * rand();

                x = targetPosition(1) + targetJammerDistance * cos(randomAngle);
                y = targetPosition(2) + targetJammerDistance * sin(randomAngle);
                z = 0;
                candidatePosition = [x y z];

                distanceToBeamCenter = ...
                    targetBeam.groundDistanceTo(candidatePosition);

                if distanceToBeamCenter <= targetBeam.Radius
                    isPlaced = true;
                end
            end

            position = candidatePosition;
        end
    end
end